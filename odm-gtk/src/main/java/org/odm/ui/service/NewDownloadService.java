    /**
     * Computes filename from URL and tracks auto-generation.
     */
    private void computeFilenameFromUrl(String url) {
        try {
            URI uri = new URI(url);
            String path = uri.getPath();
            if (path != null && !path.isEmpty()) {
                String filename = path.substring(path.lastIndexOf('/') + 1);
                if (!filename.isEmpty()) {
                    setFilenameText(filename);
                    // Track that this filename was auto-generated (Requirement 3)
                    filenameAutoGenerated = true;
                    lastAutoGeneratedFilename = filename;
                    LOGGER.fine("Auto-generated filename from URL: " + filename);
                } else {
                    // Fall back to a default name
                    String defaultName = "download";
                    setFilenameText(defaultName);
                    filenameAutoGenerated = true;
                    lastAutoGeneratedFilename = defaultName;
                    LOGGER.fine("Used default filename: " + defaultName);
                }
            } else {
                // No path in URL, use default
                String defaultName = "download";
                setFilenameText(defaultName);
                filenameAutoGenerated = true;
                lastAutoGeneratedFilename = defaultName;
                LOGGER.fine("No path in URL, used default filename: " + defaultName);
            }
        } catch (Exception e) {
            LOGGER.fine("Could not compute filename from URL: " + e.getMessage());
            // Set default filename on error
            String defaultName = "download";
            setFilenameText(defaultName);
            filenameAutoGenerated = true;
            lastAutoGeneratedFilename = defaultName;
        }
    }

