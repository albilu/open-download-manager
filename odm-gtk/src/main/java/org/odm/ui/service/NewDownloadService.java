    /**
     * Determines the category from the URL.
     */
    private String determineCategoryFromUrl(String url) {
        String lowerUrl = url.toLowerCase();

        // Video formats and streaming sites
        if (isYoutubeDlpUrl(lowerUrl) || lowerUrl.matches(".*\\.(mp4|webm|flv|mkv|avi|mov|wmv|m4v)$")) {
            return "Video";
        }

        // Audio formats
        if (lowerUrl.matches(".*\\.(mp3|flac|ogg|wav|aac|m4a|wma)$")) {
            return "Audio";
        }

        // Archives
        if (lowerUrl.matches(".*\\.(zip|rar|7z|tar|gz|bz2|xz)$")) {
            return "Archive";
        }

        // Documents
        if (lowerUrl.matches(".*\\.(pdf|doc|docx|txt|rtf|odt)$")) {
            return "Document";
        }

        // Images
        if (lowerUrl.matches(".*\\.(jpg|jpeg|png|gif|bmp|svg|webp)$")) {
            return "Image";
        }

        // Software
        if (lowerUrl.matches(".*\\.(exe|msi|deb|rpm|dmg|pkg|appimage)$")) {
            return "Software";
        }

        return "Others";
    }

