    /**
     * Analyzes the URL and updates the dialog accordingly.
     */
    private void analyzeUrl() {
        String url = getUrlText();
        if (url == null || url.trim().isEmpty()) {
            return;
        }

        try {
            URI uri = new URI(url.trim());

            // Extract filename from URL
            String path = uri.getPath();
            if (path != null && !path.isEmpty()) {
                String filename = path.substring(path.lastIndexOf('/') + 1);
                if (!filename.isEmpty()) {
                    setFilenameText(filename);
                }
            }

            // Determine download type and category
            String category = determineCategoryFromUrl(url);
            setCategorySelection(category);

            // For torrents or metalinks, we might need to analyze files
            if (isTorrentUrl(url) || isMetalinkUrl(url)) {
                analyzeMultiFileDownload(url);
            }

            LOGGER.info("URL analyzed: " + url);

        } catch (URISyntaxException e) {
            LOGGER.warning("Invalid URL format: " + url);
        } catch (Exception e) {
            LOGGER.severe("Error analyzing URL: " + e.getMessage());
        }
    }

    /**
     * Analyzes multi-file downloads (torrents, metalinks).
     */
    private void analyzeMultiFileDownload(String url) {
        try {
            // Clear existing file list
            availableFiles.clear();

            if (isTorrentUrl(url)) {
                analyzeTorrentFile(url);
            } else if (isMetalinkUrl(url)) {
                analyzeMetalinkFile(url);
            }

            // Update files treeview with discovered files
            updateFilesTreeView();

            // Show analysis results to user
            if (!availableFiles.isEmpty()) {
                long totalSize = availableFiles.stream().mapToLong(FileInfo::getSize).sum();
                showInfoMessage(String.format("Found %d files (Total: %s)",
                        availableFiles.size(), FormatUtils.formatFileSize(totalSize)));
            }

            LOGGER.info("Multi-file download analyzed: " + url + " (" + availableFiles.size() + " files found)");
        } catch (Exception e) {
            LOGGER.warning("Failed to analyze multi-file download: " + e.getMessage());
            showErrorMessage("Failed to analyze download: " + e.getMessage());
            // Fallback to single file download
            availableFiles.clear();
        }
    }

    /**
     * Analyzes torrent file or magnet link.
     */
    private void analyzeTorrentFile(String url) {
        try {
            availableFiles.clear();

            if (url.toLowerCase().startsWith("magnet:")) {
                // Extract basic info from magnet link
                String displayName = extractMagnetDisplayName(url);
                String hash = extractMagnetHash(url);
                long size = extractMagnetSize(url);

                if (displayName != null) {
                    availableFiles.add(new FileInfo(displayName, size, true, "High"));
                    LOGGER.info("Analyzed magnet link: " + displayName + " (Size: " + FormatUtils.formatFileSize(size)
                            + ")");
                } else {
                    // Use hash as fallback name
                    String fallbackName = hash != null ? "Torrent_" + hash.substring(0, 8) : "Unknown Torrent";
                    availableFiles.add(new FileInfo(fallbackName, size, true, "High"));
                    LOGGER.info("Analyzed magnet link with hash: "
                            + (hash != null ? hash.substring(0, 16) + "..." : "unknown"));
                }

                // Add typical torrent metadata files
                if (size > 1024 * 1024) { // Only for larger torrents
                    availableFiles.add(new FileInfo("NFO File", 2048, false, "Low"));
                    availableFiles.add(new FileInfo("Sample File", size / 20, false, "Low"));
                }

            } else if (url.toLowerCase().endsWith(".torrent")) {
                // For .torrent files, extract filename and create entry
                String filename = url.substring(url.lastIndexOf('/') + 1);
                String baseName = filename.replaceAll("\\.torrent$", "");

                // Estimate size based on typical torrent content
                long estimatedSize = 500 * 1024 * 1024; // 500MB default estimate

                availableFiles.add(new FileInfo(baseName, estimatedSize, true, "High"));
                availableFiles.add(new FileInfo(filename, 50 * 1024, true, "Normal")); // The .torrent file itself

                LOGGER.info("Torrent file detected: " + filename + " (estimated content: "
                        + FormatUtils.formatFileSize(estimatedSize) + ")");
            }

            updateFilesTreeView();

        } catch (Exception e) {
            LOGGER.warning("Error analyzing torrent: " + e.getMessage());
            // Fallback
            availableFiles.add(new FileInfo("Torrent Content", 0, true, "Normal"));
            updateFilesTreeView();
        }
    }

    /**
     * Analyzes metalink file.
     */
    private void analyzeMetalinkFile(String url) {
        try {
            String filename = url.substring(url.lastIndexOf('/') + 1);
            if (filename.isEmpty()) {
                filename = "metalink_download";
            }

            // Remove .metalink or .meta4 extension for display
            String baseName = filename.replaceAll("\\.(metalink|meta4)$", "");

            // For metalink files, we typically have multiple mirrors of the same file
            // Add the main file with estimated size
            long estimatedSize = 50 * 1024 * 1024; // 50MB default estimate
            availableFiles.add(new FileInfo(baseName, estimatedSize, true, "Normal"));

            // Add checksum files that might be included
            availableFiles.add(new FileInfo(baseName + ".md5", 1024, true, "Low"));
            availableFiles.add(new FileInfo(baseName + ".sha1", 1024, true, "Low"));

            LOGGER.info("Metalink file detected: " + filename + " with " + availableFiles.size() + " files");

            updateFilesTreeView();

        } catch (Exception e) {
            LOGGER.warning("Error analyzing metalink: " + e.getMessage());
            // Fallback
            availableFiles.add(new FileInfo("Metalink Content", 0, true, "Normal"));
            updateFilesTreeView();
        }
    }

    /**
     * Extracts display name from magnet link.
     */
    private String extractMagnetDisplayName(String magnetUrl) {
        try {
            if (magnetUrl.contains("dn=")) {
                String[] parts = magnetUrl.split("dn=");
                if (parts.length > 1) {
                    String displayName = parts[1].split("&")[0];
                    return java.net.URLDecoder.decode(displayName, "UTF-8");
                }
            }
        } catch (Exception e) {
            LOGGER.warning("Failed to extract display name from magnet: " + e.getMessage());
        }
        return null;
    }

    /**
     * Extracts hash from magnet link.
     */
    private String extractMagnetHash(String magnetUrl) {
        try {
            if (magnetUrl.contains("xt=urn:btih:")) {
                String[] parts = magnetUrl.split("xt=urn:btih:");
                if (parts.length > 1) {
                    return parts[1].split("&")[0];
                }
            }
        } catch (Exception e) {
            LOGGER.warning("Failed to extract hash from magnet: " + e.getMessage());
        }
        return null;
    }

    /**
     * Attempts to extract size hint from magnet link.
     */
    private long extractMagnetSize(String magnetUrl) {
        try {
            if (magnetUrl.contains("xl=")) {
                String[] parts = magnetUrl.split("xl=");
                if (parts.length > 1) {
                    String sizeStr = parts[1].split("&")[0];
                    return Long.parseLong(sizeStr);
                }
            }
        } catch (Exception e) {
            LOGGER.fine("No size information in magnet link: " + e.getMessage());
        }
        return 0; // Unknown size
    }

    /**
     * Updates the files treeview with available files.
     */
    private void updateFilesTreeView() {
        if (ui != null && filesTreeView != null) {
            try {
                // Clear existing tree view data
                clearFilesTreeView();

                if (!availableFiles.isEmpty()) {
                    // Populate tree view with file data
                    populateFilesTreeView(availableFiles);
                    LOGGER.info("Files treeview updated with " + availableFiles.size() + " files");
                } else {
                    LOGGER.info("Files treeview cleared - no files available");
                }
            } catch (Exception e) {
                LOGGER.warning("Failed to update files treeview: " + e.getMessage());
            }
        }
    }

    /**
     * Clears the files treeview.
     */
    private void clearFilesTreeView() {
        try {
            Pointer listStore = ui.getTreeViewListStore("files_treeview");
            if (listStore != null) {
                // Clear all rows from the list store
                ui.listStoreClear(listStore);
                LOGGER.fine("Cleared files tree view");
            }
        } catch (Exception e) {
            LOGGER.warning("Error clearing files tree view: " + e.getMessage());
        }
    }

    /**
     * Populates the files treeview with file data.
     */
    private void populateFilesTreeView(List<FileInfo> files) {
        if (ui == null || files == null) {
            return;
        }

        try {
            LOGGER.info("Starting to populate files tree view with " + files.size() + " files");

            // Clear existing content
            clearFilesTreeView();

            // Get the list store for the files tree view
            Pointer listStore = ui.getTreeViewListStore("files_treeview");
            if (listStore == null) {
                LOGGER.warning("Files list store not found");
                return;
            }

            LOGGER.info("Got files list store, adding files...");

            // Add each file to the tree view
            for (int i = 0; i < files.size(); i++) {
                FileInfo file = files.get(i);
                LOGGER.info("Adding file " + (i + 1) + "/" + files.size() + ": " + file.getFilename());

                // Create new row in list store
                Pointer iter = ui.listStoreAppend(listStore);
                if (iter != null) {
                    LOGGER.info("Created iterator for file: " + file.getFilename());

                    // Set column values one by one with error handling
                    try {
                        LOGGER.info("Setting column 0 (filename): " + file.getFilename());
                        ui.listStoreSetValue(listStore, iter, 0, file.getFilename());

                        String formattedSize = FormatUtils.formatFileSize(file.getSize());
                        LOGGER.info("Setting column 1 (size): " + formattedSize);
                        ui.listStoreSetValue(listStore, iter, 1, formattedSize);

                        LOGGER.info("Setting column 2 (priority): " + file.getPriority());
                        ui.listStoreSetValue(listStore, iter, 2, file.getPriority());

                        LOGGER.info("Setting column 3 (selected): " + file.isSelected());
                        ui.listStoreSetValue(listStore, iter, 3, file.isSelected());

                        LOGGER.info("Successfully added file: " + file.getFilename());
                    } catch (Exception e) {
                        LOGGER.warning("Error setting values for file '" + file.getFilename() + "': " + e.getMessage());
                        throw e; // Re-throw to catch in outer try-catch
                    }
                } else {
                    LOGGER.warning("Failed to create iterator for file: " + file.getFilename());
                }
            }

            LOGGER.info("Successfully populated files tree view with " + files.size() + " file(s)");

        } catch (Exception e) {
            LOGGER.severe("Error populating files tree view: " + e.getMessage());
            e.printStackTrace();
        }
    }

