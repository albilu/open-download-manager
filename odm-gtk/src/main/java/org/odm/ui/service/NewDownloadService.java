    /**
     * Previews what download type would be detected for the current URL.
     * Useful for debugging and testing type detection logic.
     *
     * @return the detected download type
     */
    public org.manager.download.Download.Type previewDownloadType() {
        try {
            String url = getUrlText();
            if (url == null || url.trim().isEmpty()) {
                return org.manager.download.Download.Type.ARIA2; // Default
            }

            String lowerUrl = url.toLowerCase().trim();

            // Check manual override
            org.manager.download.Download.Type overrideType = getManualTypeOverride();
            if (overrideType != null && validateTypeForUrl(overrideType, lowerUrl)) {
                return overrideType;
            }

            // Check proxy configuration
            boolean hasProxy = isProxyEnabled();
            if (hasProxy) {
                String proxyHost = ui.getEntryText("proxy_host_entry");
                int proxyPort = ui.getSpinButtonValueAsInt("proxy_port_spin");
                if (proxyHost != null && !proxyHost.trim().isEmpty() && proxyPort > 0) {
                    return org.manager.download.Download.Type.PROXYCHAINS;
                }
            }

            // Check yt-dlp URLs
            if (isYoutubeDlpUrl(lowerUrl)) {
                return org.manager.download.Download.Type.YOUTUBE;
            }

            // Check Tor-enabled aria2 URLs
            boolean torEnabled = isTorEnabled();
            if (torEnabled && isAria2SupportedUrl(lowerUrl) && !isTorrentUrl(lowerUrl)) {
                return org.manager.download.Download.Type.TOR;
            }

            // Default to ARIA2
            return org.manager.download.Download.Type.ARIA2;

        } catch (Exception e) {
            LOGGER.warning("Error previewing download type: " + e.getMessage());
            return org.manager.download.Download.Type.ARIA2; // Safe fallback
        }
    }

