    /**
     * Validates the input, optionally showing error messages.
     */
    private boolean validateInput(boolean showErrors) {
        String url = getUrlText();
        String torrentFile = null;

        // Check if we have a torrent file selected
        try {
            if (ui != null) {
                torrentFile = ui.getFileChooserFilename("torrent_file_chooser");
            }
        } catch (Exception e) {
            // Ignore torrent file check error
        }

        boolean hasTorrentFile = torrentFile != null && !torrentFile.trim().isEmpty();
        boolean hasUrl = url != null && !url.trim().isEmpty();

        // Must have either URL or torrent file
        if (!hasUrl && !hasTorrentFile) {
            if (showErrors) {
                showErrorMessage("Please enter a URL or select a torrent file");
            }
            return false;
        }

        // If we have a URL, validate it
        if (hasUrl && !url.trim().isEmpty()) {
            try {
                URI uri = new URI(url.trim());
                if (uri.getScheme() == null) {
                    if (showErrors) {
                        showErrorMessage("URL must include protocol (http://, https://, ftp://, etc.)");
                    }
                    return false;
                }
                if (!uri.getScheme().matches("^(https?|ftp|ftps|magnet|file)$")) {
                    if (showErrors) {
                        showErrorMessage("Unsupported protocol. Supported: HTTP, HTTPS, FTP, FTPS, Magnet, File");
                    }
                    return false;
                }
            } catch (URISyntaxException e) {
                if (showErrors) {
                    showErrorMessage("Invalid URL format: " + e.getMessage());
                }
                return false;
            }
        }

        String destination = getDestinationPath();
        if (destination == null || destination.trim().isEmpty()) {
            if (showErrors) {
                showErrorMessage("Please select a destination folder");
            }
            return false;
        }

        // Validate destination exists and is writable
        try {
            Path destPath = Paths.get(destination);
            if (!destPath.toFile().exists()) {
                if (showErrors) {
                    showErrorMessage("Destination directory does not exist");
                }
                return false;
            }
            if (!destPath.toFile().isDirectory()) {
                if (showErrors) {
                    showErrorMessage("Destination must be a directory");
                }
                return false;
            }
            if (!destPath.toFile().canWrite()) {
                if (showErrors) {
                    showErrorMessage("No write permission for destination directory");
                }
                return false;
            }
        } catch (Exception e) {
            if (showErrors) {
                showErrorMessage("Invalid destination path: " + e.getMessage());
            }
            return false;
        }

        // Validate filename if provided
        String filename = getFilenameText();
        if (filename != null && !filename.trim().isEmpty()) {
            if (filename.contains("/") || filename.contains("\\")
                    || filename.contains("<") || filename.contains(">")
                    || filename.contains(":") || filename.contains("\"")
                    || filename.contains("|") || filename.contains("?")
                    || filename.contains("*")) {
                if (showErrors) {
                    showErrorMessage("Filename contains invalid characters");
                }
                return false;
            }
        }

        if (showErrors) {
            LOGGER.info("Input validation passed");
        }
        return true;
    }

