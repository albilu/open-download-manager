    /**
     * Populates the Files tab when switched to it.
     * Supports URLs, magnet links, and torrent/metalink files (Requirement 9).
     */
    private void populateFilesTab() {
        String url = getUrlText();
        String torrentFileTemp = null;

        // Check if we have a torrent file selected
        try {
            if (ui != null) {
                torrentFileTemp = ui.getFileChooserFilename("torrent_file_chooser");
            }
        } catch (Exception e) {
            LOGGER.fine("Error getting torrent file: " + e.getMessage());
        }

        final String torrentFile = torrentFileTemp; // Make final for lambda usage

        boolean hasUrl = url != null && !url.trim().isEmpty();
        boolean hasTorrentFile = torrentFile != null && !torrentFile.trim().isEmpty();

        // Must have either URL or torrent file to populate files (Requirement 9)
        if (!hasUrl && !hasTorrentFile) {
            clearFilesTreeView();
            return;
        }

        // Show spinner during processing (Requirement 9)
        showSpinner(true);

        try {
            java.util.List<java.util.Map<String, Object>> files;

            if (hasTorrentFile) {
                // Handle torrent/metalink file (Requirement 9)
                LOGGER.info("Loading files from torrent/metalink file: " + torrentFile);
                files = getFilesForTorrentFile(torrentFile);
            } else {
                // Handle URL/magnet link (Requirement 9)
                LOGGER.info("Loading files from URL/magnet: " + url.trim());
                files = getFilesForUrl(url.trim());
            }

            // Convert Map-based files to FileInfo objects
            java.util.List<FileInfo> fileInfoList = convertMapFilesToFileInfo(files);

            // Update UI directly on GTK main thread
            showSpinner(false);
            populateFilesTreeView(fileInfoList);
            LOGGER.info("Files tab populated with " + fileInfoList.size() + " files");

        } catch (Exception e) {
            LOGGER.warning("Error populating files tab: " + e.getMessage());
            showSpinner(false);
        }
    }

