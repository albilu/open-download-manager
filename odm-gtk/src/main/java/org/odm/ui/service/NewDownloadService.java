    /**
     * Handles URL entry text change.
     */
    public void handleUrlEntryChanged() {
        String url = getUrlText();
        boolean hasUrl = url != null && !url.trim().isEmpty();

        if (hasUrl) {
            try {
                new URI(url.trim());
                // Auto-compute filename when URL changes
                String currentFilename = getFilenameText();

                // Update filename if:
                // 1. Filename is empty or default
                // 2. Filename was previously auto-generated and hasn't been manually changed
                boolean shouldUpdateFilename = currentFilename == null
                        || currentFilename.trim().isEmpty()
                        || currentFilename.equals("download")
                        || (filenameAutoGenerated && currentFilename.equals(lastAutoGeneratedFilename));

                if (shouldUpdateFilename) {
                    computeFilenameFromUrl(url.trim());
                }
            } catch (URISyntaxException e) {
                // Invalid URL, but we'll let validateInput handle the details
            }
        }

        // Enable/disable analyze button based on URL presence
        if (ui != null) {
            ui.setWidgetSensitive("analyze_button", hasUrl);
        }

        // Update input method exclusivity (this may clear torrent file if URL is
        // entered)
        updateInputMethodExclusivity();

        // Update start button state based on complete validation
        updateStartButtonState();

        LOGGER.fine("URL changed: " + (hasUrl ? "has content" : "empty"));
    }

